import json
import os
from pathlib import Path
from shutil import which

from goodteam_os.models import _parse_simple_yaml
from goodteam_os.project_reviewer_profiles import reviewer_profiles_report
from goodteam_os.reviewer_dispatch import reviewer_dispatch_diagnostics
from goodteam_os.staging import deployment_backend_report, delivery_contract_report
from goodteam_os.workers import worker_backend_doctor


ProjectTarget = dict[str, object]

WORKER_MODES = ("fake", "codex", "anthropic", "gemini", "opencode", "pi", "pi-rpc", "noop", "human", "manual")
DELIVERY_MODES = (
    "mvp",
    "init_project",
    "multi_service",
    "static_site",
    "cli_tool",
    "library",
    "data_pipeline",
    "mobile_app",
    "feature_increment",
    "custom",
)


def load_project_target(config_path: Path) -> ProjectTarget:
    return _parse_simple_yaml(config_path)


def _slug(value: str) -> str:
    cleaned = "".join(char.lower() if char.isalnum() else "-" for char in value.strip())
    return "-".join(part for part in cleaned.split("-") if part) or "project"


def _yaml_scalar(value: object) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def build_registered_project_config(
    key: str,
    name: str,
    root: Path,
    *,
    model_profile: str = "balanced",
    worker_mode: str = "codex",
) -> str:
    return (
        f"name: {_yaml_scalar(name)}\n"
        f"key: {_yaml_scalar(key)}\n"
        "source_type: unconfirmed\n"
        f"model_profile: {_yaml_scalar(model_profile)}\n"
        "delivery_mode: init_project\n"
        "repos:\n"
        f"  root: {_yaml_scalar(root.resolve())}\n"
        "worker_backend:\n"
        f"  mode: {_yaml_scalar(worker_mode)}\n"
        "task_backend:\n"
        "  mode: local\n"
        "  sync: \n"
    )


def build_project_config(
    key: str,
    name: str,
    *,
    repo_path: str = "",
    model_profile: str = "balanced",
    worker_mode: str = "fake",
    delivery_mode: str = "mvp",
) -> str:
    """Render a parseable starter project config.

    Defaults to the ``fake`` worker so a brand-new user can reach their first
    approval gate with no model credentials, then switch ``worker_backend.mode``
    to ``codex`` once a real CLI worker is configured."""
    if worker_mode not in WORKER_MODES:
        raise ValueError(f"worker_mode must be one of {WORKER_MODES}, got {worker_mode!r}")
    if delivery_mode not in DELIVERY_MODES:
        raise ValueError(f"delivery_mode must be one of {DELIVERY_MODES}, got {delivery_mode!r}")
    repo = repo_path.strip() or "."
    return f"""# GoodTeam project config — generated by `goodteam-os init`.
# This file is local and gitignored; it holds machine-specific repo paths.
# Edit the repo path(s) and switch worker_backend.mode to `codex` for real runs.
name: {name}
key: {key.upper()}
model_profile: {model_profile}
delivery_mode: {delivery_mode}
source_type: existing_project
repos:
  app: {repo}
worker_backend:
  mode: {worker_mode}
workers:
  ui: {worker_mode}
  implementation: {worker_mode}
  qa: {worker_mode}
task_backend:
  mode: local
# Optional reviewer profile opt-in. Leave commented to keep zero-profile default.
# reviewer_profiles:
#   implementation:
#     - correctness-security
#   release:
#     - product-operator
delivery_contract:
  required: false
"""


def write_project_config(
    projects_dir: Path,
    key: str,
    name: str,
    *,
    repo_path: str = "",
    model_profile: str = "balanced",
    worker_mode: str = "fake",
    delivery_mode: str = "mvp",
    force: bool = False,
) -> Path:
    projects_dir.mkdir(parents=True, exist_ok=True)
    path = projects_dir / f"{_slug(key)}.local.yaml"
    if path.exists() and not force:
        raise FileExistsError(
            f"{path} already exists. Pass force=True (CLI: --force) to overwrite it."
        )
    path.write_text(
        build_project_config(
            key=key,
            name=name,
            repo_path=repo_path,
            model_profile=model_profile,
            worker_mode=worker_mode,
            delivery_mode=delivery_mode,
        ),
        encoding="utf-8",
    )
    return path


def init_project(
    *,
    projects_dir: Path,
    key: str,
    name: str,
    repo_path: str = "",
    model_profile: str = "balanced",
    worker_mode: str = "fake",
    delivery_mode: str = "mvp",
    force: bool = False,
) -> dict[str, object]:
    path = write_project_config(
        projects_dir,
        key=key,
        name=name,
        repo_path=repo_path,
        model_profile=model_profile,
        worker_mode=worker_mode,
        delivery_mode=delivery_mode,
        force=force,
    )
    target = load_project_target(path)
    return {
        "config_path": str(path),
        "doctor": check_project_target(target),
    }


def update_worker_backend_config(
    config_path: Path,
    *,
    mode: str,
    workers: dict[str, str],
    role_model_overrides: dict[str, str] | None = None,
) -> None:
    """Update only worker backend blocks in a local project config."""
    lines = config_path.read_text(encoding="utf-8").splitlines(keepends=True)
    worker_backend_block = ["worker_backend:\n", f"  mode: {mode}\n"]
    worker_lines = [f"  {role}: {backend}\n" for role, backend in workers.items()]
    workers_block = ["workers:\n", *worker_lines] if worker_lines else []

    lines = _replace_or_append_top_level_block(lines, "worker_backend", worker_backend_block)
    lines = _replace_or_append_top_level_block(lines, "workers", workers_block)
    if role_model_overrides is not None:
        model_lines = [f"  {role}: {model}\n" for role, model in role_model_overrides.items()]
        model_block = ["role_model_overrides:\n", *model_lines] if model_lines else []
        lines = _replace_or_append_top_level_block(lines, "role_model_overrides", model_block)
    config_path.write_text("".join(lines), encoding="utf-8")


def _replace_or_append_top_level_block(lines: list[str], key: str, replacement: list[str]) -> list[str]:
    block = _find_top_level_block(lines, key)
    if block is not None:
        start, end = block
        return [*lines[:start], *replacement, *lines[end:]]
    if not replacement:
        return lines
    appended = list(lines)
    if appended and not appended[-1].endswith("\n"):
        appended[-1] = f"{appended[-1]}\n"
    return [*appended, *replacement]


def _find_top_level_block(lines: list[str], key: str) -> tuple[int, int] | None:
    header = f"{key}:"
    for index, line in enumerate(lines):
        if line.startswith(header):
            end = index + 1
            while end < len(lines) and (_is_more_indented(lines[end]) or not lines[end].strip()):
                end += 1
            return index, end
    return None


def _is_more_indented(line: str) -> bool:
    return line.startswith(" ") or line.startswith("\t")


def _read_env_file(env_file: Path) -> dict[str, str]:
    if not env_file.is_file():
        return {}

    values: dict[str, str] = {}
    for raw_line in env_file.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line.removeprefix("export ").strip()
        if "=" not in line:
            continue

        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if not key:
            continue
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
            value = value[1:-1]
        values[key] = value
    return values


def _env_value(name: str, env_file: str = "") -> str:
    if not name:
        return ""

    value = os.getenv(name)
    if value:
        return value
    if not env_file:
        return ""

    return _read_env_file(Path(env_file)).get(name, "")


def check_project_target(target: ProjectTarget) -> dict[str, object]:
    repos = {
        name: {
            "path": path,
            "exists": Path(str(path)).is_dir(),
        }
        for name, path in dict(target.get("repos", {})).items()
    }
    workers = {}
    for role, command in dict(target.get("workers", {})).items():
        resolved = which(str(command))
        workers[role] = {
            "command": str(command),
            "available": resolved is not None,
            "path": resolved or "",
        }
    providers = {}
    for name, provider in dict(target.get("providers", {})).items():
        provider_data = dict(provider)
        api_key_env = str(provider_data.get("api_key_env", ""))
        env_file = str(provider_data.get("env_file", ""))
        providers[name] = {
            "type": str(provider_data.get("type", "")),
            "base_url": str(provider_data.get("base_url", "")),
            "api_key_env": api_key_env,
            "env_file": env_file,
            "configured": bool(_env_value(api_key_env, env_file)),
        }

    global_mode = str(dict(target.get("worker_backend", {})).get("mode", "codex") or "codex")
    role_worker_backends = {
        str(role): (str(backend).strip() or global_mode)
        for role, backend in dict(target.get("workers", {})).items()
        if str(role).strip()
    }
    distinct_backends = sorted({global_mode, *role_worker_backends.values()})
    return {
        "project": {
            "name": target.get("name", ""),
            "key": target.get("key", ""),
            "plane_project_id": target.get("plane_project_id", ""),
        },
        "repos": repos,
        "workers": workers,
        "providers": providers,
        "role_routes": target.get("role_routes", {}),
        "worker_backend_preflight": worker_backend_doctor(global_mode),
        "role_worker_backends": role_worker_backends,
        "worker_backends_preflight": {backend: worker_backend_doctor(backend) for backend in distinct_backends},
        "reviewer_profiles": reviewer_profiles_report(target, backend_doctor=worker_backend_doctor),
        "reviewer_dispatch": reviewer_dispatch_diagnostics(target),
        "deployment_backend": deployment_backend_report(target, ssh_available=bool(which("ssh"))),
        "delivery_contract": delivery_contract_report(target),
    }
