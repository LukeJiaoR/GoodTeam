import { test, expect, importProject } from './fixtures.js';
import { clickMutation, prepareFirstTask, sendTask } from './business-loop-helpers.js';

test('review editing and change discussion stay in the current task', async ({ page, fixture }, testInfo) => {
  await importProject(page, fixture);
  await sendTask(page, fixture, 'Implement title search.');
  await prepareFirstTask(page, fixture, []);
  await expect(page).toHaveURL(new RegExp(`/projects/${fixture.key}/work$`));
  await expect(page.getByRole('button', { name: 'Inspect details →', exact: true })).toBeVisible();
  const url = page.url();
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Keep this separate question.');
  await page.getByRole('button', { name: 'Inspect details →', exact: true }).click();
  const detail = page.getByRole('dialog');
  const fullReview = detail.getByRole('button', { name: 'Review document', exact: true });
  if (await fullReview.count()) await fullReview.first().click();
  const review = page.getByRole('dialog', { name: 'Review', exact: true });
  await expect(review).toBeVisible();
  expect(page.url()).toBe(url);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await review.evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('review-panel-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await review.getByRole('button', { name: 'Edit Source', exact: true }).click();
  const editor = review.getByRole('textbox', { name: 'Artifact content', exact: true });
  const original = await editor.inputValue();
  await editor.fill(`${original}\n\nUnsaved note.`);
  await review.getByRole('button', { name: 'Back to task', exact: true }).click();
  const warning = page.getByRole('dialog', { name: 'Unsaved review edits' });
  await expect(warning).toBeVisible();
  await warning.getByRole('button', { name: 'Keep editing', exact: true }).click();
  await expect(editor).toHaveValue(`${original}\n\nUnsaved note.`);
  await editor.fill(original);
  await page.screenshot({ path: testInfo.outputPath('review-panel.png'), fullPage: true });
  await clickMutation(page, review.getByRole('button', { name: 'Request changes', exact: true }), '/api/intent-commit/start');
  await expect(review).toHaveCount(0);
  expect(page.url()).toBe(url);
  await expect(page.getByRole('textbox', { name: 'What should change?', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Message', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toHaveValue('Keep this separate question.');
});

test('approval from the document panel stays bound to the displayed run and evidence', async ({ page, fixture }) => {
  await importProject(page, fixture);
  await sendTask(page, fixture, 'Implement title search.');
  const runId = await prepareFirstTask(page, fixture, []);
  await expect(page).toHaveURL(new RegExp(`/projects/${fixture.key}/work$`));
  await expect(page.getByRole('button', { name: 'Inspect details →', exact: true })).toBeVisible();
  const url = page.url();
  await page.getByRole('button', { name: 'Inspect details →', exact: true }).click();
  const fullReview = page.getByRole('dialog').getByRole('button', { name: 'Review document', exact: true });
  if (await fullReview.count()) await fullReview.first().click();
  const review = page.getByRole('dialog', { name: 'Review', exact: true });
  await expect(review.getByRole('button', { name: 'Approve', exact: true })).toBeEnabled();
  const request = page.waitForRequest((item) => item.url().endsWith('/api/approve') && item.method() === 'POST');
  await clickMutation(page, review.getByRole('button', { name: 'Approve', exact: true }), '/api/approve');
  const binding = (await request).postDataJSON();
  expect(binding).toMatchObject({ expected_run_id: runId, expected_target_type: 'review', expected_target_id: 'takeover' });
  expect(binding.expected_artifact_version).toMatch(/^sha256:/);
  expect(page.url()).toBe(url);
  await review.getByRole('button', { name: 'Back to task', exact: true }).click();
  await expect(review).toHaveCount(0);
  expect(page.url()).toBe(url);
  const response = await page.request.get(`/api/state?project=${fixture.key}`);
  expect((await response.json()).state.next_node).toBe('await_prd_approval');
});
