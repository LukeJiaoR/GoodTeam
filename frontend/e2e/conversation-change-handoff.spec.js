import { test, expect, importProject } from './fixtures.js';
import { clickMutation, decisions, prepareFirstTask, sendTask, snapshot } from './business-loop-helpers.js';

test('typed requirements become an exact saved discussion, never an implicit execution change', async ({ page, fixture }, testInfo) => {
  const evidence = [];
  await importProject(page, fixture);
  await sendTask(page, fixture, 'Implement title search.');
  await prepareFirstTask(page, fixture, evidence);
  const before = await snapshot(page, fixture, evidence);
  const boundary = page.getByRole('note', { name: 'How this message affects the task' });
  await expect(boundary).toHaveAttribute('data-state', 'message');
  const text = '  Web only.\n\n    no_new_dependencies()\n';
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill(text);
  await clickMutation(page, boundary.getByRole('button', { name: 'Discuss a task change' }), '/api/intent-commit/start');
  await expect(boundary).toHaveAttribute('data-state', 'discussing');
  await expect(page.getByRole('textbox', { name: 'What should change?', exact: true })).toHaveValue(text);
  const pending = await snapshot(page, fixture, evidence);
  expect(pending.state).toEqual(before.state);
  expect(decisions(pending)).toEqual(decisions(before));
  expect(pending.worker_jobs).toEqual(before.worker_jobs);
  expect(pending.team_workspace.attention_request.intent_commit.draft_text).toBe(text);
  await page.reload();
  await expect(boundary).toHaveAttribute('data-state', 'discussing');
  await expect(page.getByRole('textbox', { name: 'What should change?', exact: true })).toHaveValue(text);
  await page.getByRole('button', { name: 'Message', exact: true }).click();
  await expect(boundary).toHaveAttribute('data-state', 'discussing');
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toHaveValue('');
  const restored = await snapshot(page, fixture, evidence);
  expect(restored.team_workspace.attention_request.intent_commit.draft_text).toBe(text);
  expect(decisions(restored)).toEqual(decisions(before));
  await testInfo.attach('change-handoff', { body: JSON.stringify({ project: fixture.key, snapshots: evidence }, null, 2), contentType: 'application/json' });
  await testInfo.attach('change-pending', { body: await page.screenshot(), contentType: 'image/png' });
});
